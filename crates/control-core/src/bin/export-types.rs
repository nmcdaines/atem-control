use control_core::*;
use ts_rs::TS;

fn main() {
    let cfg = ts_rs::Config::default();
    let types = [
        PostgresImportSettings::decl(&cfg),
        DeviceKind::decl(&cfg),
        Framing::decl(&cfg),
        Connection::decl(&cfg),
        Device::decl(&cfg),
        Command::decl(&cfg),
        Action::decl(&cfg),
        Step::decl(&cfg),
        Macro::decl(&cfg),
        Shortcut::decl(&cfg),
        Config::decl(&cfg),
        Input::decl(&cfg),
        PipState::decl(&cfg),
        SwitcherState::decl(&cfg),
        CameraState::decl(&cfg),
        ConnectionStatus::decl(&cfg),
        Feedback::decl(&cfg),
        DeviceState::decl(&cfg),
        RunStatus::decl(&cfg),
        Run::decl(&cfg),
        NdiSource::decl(&cfg),
        NdiPreview::decl(&cfg),
        NdiSnapshot::decl(&cfg),
        Snapshot::decl(&cfg),
    ];
    let output = format!(
        "// Generated by `cargo run -p control-core --bin export-types`. Do not edit.\n{}\n",
        types
            .iter()
            .map(|t| format!("export {t}"))
            .collect::<Vec<_>>()
            .join("\n")
    );
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../apps/desktop/ui/src/bindings.ts");
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, output).unwrap();
}
